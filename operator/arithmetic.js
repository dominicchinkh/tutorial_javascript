// Arithmetic Operators Showcase

let a = 10;
let b = 3;

// 1. Addition (+)
let addition = a + b;
console.log(`Addition (${a} + ${b}):`, addition); // 13

// 2. Subtraction (-)
let subtraction = a - b;
console.log(`Subtraction (${a} - ${b}):`, subtraction); // 7

// 3. Multiplication (*)
let multiplication = a * b;
console.log(`Multiplication (${a} * ${b}):`, multiplication); // 30

// 4. Division (/)
let division = a / b;
console.log(`Division (${a} / ${b}):`, division); // 3.3333333333333335

// 5. Remainder / Modulo (%)
// Returns the remainder left over when one operand is divided by a second operand.
let remainder = a % b;
console.log(`Remainder (${a} % ${b}):`, remainder); // 1

// 6. Exponentiation (**)
// Calculates the base to the exponent power.
let exponentiation = a ** b;
console.log(`Exponentiation (${a} ** ${b}):`, exponentiation); // 1000

// 7. Increment (++)
// Increases an integer value by one.
let count = 5;
count++; 
console.log("Increment:", count); // 6

// 8. Decrement (--)
// Decreases an integer value by one.
count--;
console.log("Decrement:", count); // 5

// 9. Unary Negation (-)
// Returns the negation of the operand.
let negativeA = -a;
console.log("Unary Negation:", negativeA); // -10
